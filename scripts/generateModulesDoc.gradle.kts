// Generates docs/MODULES.md from the module source tree.
//
// Applied from build.gradle.kts. Run with:
//   ./gradlew generateModulesDoc
//
// The output is deterministic (packages and modules sorted by name) so CI can regenerate it and
// fail if the committed copy is stale.

import java.nio.charset.StandardCharsets

private val superCallPattern = Regex(
    """super\s*\([^;]*?"([^"]+)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)""",
    setOf(RegexOption.DOT_MATCHES_ALL)
)

private data class ModuleDoc(
    val pkg: String,
    val name: String,
    val id: String,
    val description: String
)

tasks.register("generateModulesDoc") {
    group = "documentation"
    description = "Generates docs/MODULES.md from src/main/java/.../modules/**/*.java"

    val projectDir = layout.projectDirectory.asFile
    val modulesRoot = layout.projectDirectory.dir("src/main/java/net/venomous/meteoraddon/modules")
    val outputFile = layout.projectDirectory.file("docs/MODULES.md")

    inputs.dir(modulesRoot)
    outputs.file(outputFile)

    doLast {
        val root = modulesRoot.asFile
        if (!root.isDirectory) {
            throw GradleException("Module source root not found: $root")
        }

        val modules = root.walkTopDown()
            .filter { it.isFile && it.extension == "java" && it.name != "ModuleRegistry.java" }
            .map { file ->
                val source = file.readText(StandardCharsets.UTF_8)
                val match = superCallPattern.find(source)
                val relative = file.relativeTo(root).invariantSeparatorsPath
                val pkg = relative.substringBeforeLast('/', missingDelimiterValue = "")
                    .ifEmpty { "(root)" }

                ModuleDoc(
                    pkg = pkg,
                    name = file.nameWithoutExtension,
                    id = match?.groupValues?.get(1) ?: "—",
                    description = match?.groupValues?.get(2)
                        ?.replace("\\\"", "\"")
                        ?.replace("\\n", " ")
                        ?.replace("|", "\\|")
                        ?: "—"
                )
            }
            .sortedWith(compareBy({ it.pkg }, { it.name }))
            .toList()

        val byPackage = modules.groupBy { it.pkg }
        val packageCount = byPackage.size

        val doc = buildString {
            appendLine("<!-- Generated by ./gradlew generateModulesDoc. Do not edit by hand. -->")
            appendLine()
            appendLine("# Modules")
            appendLine()
            appendLine(
                "Venomous currently ships **${modules.size}** modules across " +
                    "**$packageCount** packages. This file is generated from the source tree; " +
                    "adding a module only requires creating the class, and the next " +
                    "`generateModulesDoc` run updates this page."
            )
            appendLine()
            appendLine("| Package | Modules |")
            appendLine("| --- | ---: |")
            byPackage.forEach { (pkg, entries) ->
                appendLine("| [`$pkg`](#${pkg.replace(Regex("[^a-z0-9]+"), "-")}) | ${entries.size} |")
            }

            byPackage.forEach { (pkg, entries) ->
                appendLine()
                appendLine("## $pkg")
                appendLine()
                appendLine("| Module | ID | Description |")
                appendLine("| --- | --- | --- |")
                entries.forEach { module ->
                    appendLine("| ${module.name} | `${module.id}` | ${module.description} |")
                }
            }
        }

        val out = outputFile.asFile
        out.parentFile.mkdirs()
        out.writeText(doc, StandardCharsets.UTF_8)
        logger.lifecycle("Wrote ${modules.size} modules to ${out.toPath().let { projectDir.toPath().relativize(it) }}")
    }
}
